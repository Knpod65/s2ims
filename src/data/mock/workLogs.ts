export function getAccumulatedConfirmedHours(assignmentId: string): number {
  return mockWorkLogs
    .filter((log) => log.assignment_id === assignmentId && log.status === 'CONFIRMED')
    .reduce((total, log) => total + (log.actualConfirmedHours ?? 0), 0)
}

